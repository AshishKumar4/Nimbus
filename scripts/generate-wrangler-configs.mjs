import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildNimbusWranglerConfig } from '../packages/config/dist/index.js';

const ROOT = new URL('../', import.meta.url).pathname;
export const DEPLOYMENT_SPEC = 'apps/nimbus-deployments.json';
export const GENERATED_CONFIGS = ['apps/hosted-demo/wrangler.jsonc', 'apps/probe/wrangler.jsonc'];

/** @param {typeof import('../apps/nimbus-deployments.json')} spec */
export function nimbusAppConfigs(spec) {
  const base = buildNimbusWranglerConfig({
    name: spec.hostedDemo.development.name,
    r2BucketPrefix: spec.r2BucketPrefix,
    runtimeCache: { mode: 'byoa', bucket: spec.runtimeCache.bucket },
    runtimeCatalogSha256: spec.runtimeCatalogSha256,
    nimbusPublicDirectory: true, migrationTagPrefix: '', agent: spec.agent,
  });
  const common = {
    ...base,
    $schema: '../../node_modules/wrangler/config-schema.json',
    alias: Object.fromEntries(Object.entries(base.alias).map(([name, target]) => [name, './node_modules/@nimbus-sh/worker/node_modules/' + target])),
    observability: { enabled: true, head_sampling_rate: 1, traces: { enabled: true, head_sampling_rate: 1 } },
  };
  if (common.compatibility_flags.length === 0) delete common.compatibility_flags;
  const bindings = {
    vars: { ...base.vars, ...spec.vars },
    durable_objects: base.durable_objects,
    worker_loaders: base.worker_loaders,
    r2_buckets: base.r2_buckets,
  };
  /** @param {{ name: string; databaseName: string; databaseId: string; rateLimitNamespace: string; vars?: Record<string,string>; workers_dev?: boolean; observability?: object; routes?: object[] }} tier */
  const hostedTier = ({ name, databaseName, databaseId, rateLimitNamespace, vars, ...overrides }) => ({
    ...bindings, name, preview_urls: true, ...overrides,
    vars: { ...bindings.vars, ...spec.hostedDemo.vars, ...vars },
    d1_databases: [{ binding: 'DEMO_DB', database_name: databaseName, database_id: databaseId }],
    ratelimits: [{ name: 'ANON_RATE_LIMITER', namespace_id: rateLimitNamespace, simple: spec.hostedDemo.rateLimit }],
    triggers: { crons: spec.hostedDemo.crons },
  });
  const hosted = {
    ...common, ...hostedTier(spec.hostedDemo.development),
    assets: { ...base.assets, directory: 'dist/assets', run_worker_first: true },
    env: { staging: hostedTier(spec.hostedDemo.staging), production: hostedTier(spec.hostedDemo.production) },
  };
  const probe = {
    ...common, ...bindings, name: spec.probe.name, preview_urls: false,
    version_metadata: { binding: 'CF_VERSION_METADATA' },
    previews: { ...bindings, version_metadata: { binding: 'CF_VERSION_METADATA' } },
  };
  delete probe.placement;
  return [hosted, probe];
}

/** @param {{ root?: string; catalogPin?: string }} [options] */
export function writeNimbusAppConfigs({ root = ROOT, catalogPin } = {}) {
  const input = join(root, DEPLOYMENT_SPEC);
  const spec = JSON.parse(readFileSync(input, 'utf8'));
  if (catalogPin !== undefined) spec.runtimeCatalogSha256 = catalogPin;
  const configs = nimbusAppConfigs(spec);
  const outputs = GENERATED_CONFIGS.map((path, index) => [join(root, path), '// Generated by scripts/generate-wrangler-configs.mjs from apps/nimbus-deployments.json.\n' + JSON.stringify(configs[index], null, 2) + '\n']);
  if (catalogPin !== undefined) outputs.push([input, JSON.stringify(spec, null, 2) + '\n']);
  for (const [path, contents] of outputs) writeFileSync(path, contents);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) writeNimbusAppConfigs();
