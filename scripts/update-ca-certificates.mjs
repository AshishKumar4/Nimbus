#!/usr/bin/env bun
// update-ca-certificates.mjs — the trust store every session reads at
// /etc/ssl/certs/ca-certificates.crt (core vfs/ca-certificates-vfs.ts), from
// Mozilla's roots as curl.se extracts and publishes them, pinned by sha256.
//
//   bun scripts/update-ca-certificates.mjs <date> <sha256>
//
// <date> names a published extract (https://curl.se/docs/caextract.html lists
// each with its sha256); the download must hash to <sha256> or nothing is
// written. Writes packages/core/src/vfs/ca-certificates.generated.ts. The
// pin in tests/unit/ca-certificates.mjs moves with it, by hand: that test is
// what says a bundle is the one meant.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [date, pinned] = process.argv.slice(2);
if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? '') || !/^[0-9a-f]{64}$/.test(pinned ?? '')) {
  console.error('usage: bun scripts/update-ca-certificates.mjs <YYYY-MM-DD> <sha256>');
  process.exit(2);
}
const source = `https://curl.se/ca/cacert-${date}.pem`;
const response = await fetch(source);
if (!response.ok) throw new Error(`${source}: HTTP ${response.status}`);
const bytes = new Uint8Array(await response.arrayBuffer());
const sha256 = createHash('sha256').update(bytes).digest('hex');
if (sha256 !== pinned) throw new Error(`${source}: sha256 ${sha256}, not the pinned ${pinned}`);
const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
const asOf = /^## Certificate data from Mozilla as of: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const roots = text.split('-----BEGIN CERTIFICATE-----').length - 1;

const out = fileURLToPath(new URL('../packages/core/src/vfs/ca-certificates.generated.ts', import.meta.url));
writeFileSync(out, `// Generated by scripts/update-ca-certificates.mjs; do not edit.
// Source: ${source}
// Mozilla's certdata.txt as of ${asOf}; ${roots} roots.
// sha256 ${sha256}
/** The trust store's bytes, as published. */
export const CA_CERTIFICATES_PEM = ${JSON.stringify(text)};
/** When its roots were Mozilla's, for the file's mtime. */
export const CA_CERTIFICATES_DATE = ${JSON.stringify(`${date}T00:00:00Z`)};
`);
console.log(`ca-certificates: ${roots} roots from ${source} (Mozilla as of ${asOf}), sha256 ${sha256}`);
