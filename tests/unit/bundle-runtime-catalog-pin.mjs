#!/usr/bin/env bun

// `bundle-runtime.mjs --pin-catalog` regenerates the build-time root of trust
// that runtime-catalog.ts verifies catalog/v1.json against. Two properties
// matter and neither is visible to the supervisor's own tests:
//
//   1. It writes the digest of the bytes it actually fetched. A pin that is
//      merely present would disable the colo cache on every deploy while
//      looking configured.
//   2. Only the production bucket may rewrite it. The constant describes what
//      the deployed Worker's NIMBUS_RUNTIME_CACHE binding reads, so a publish
//      to an isolated bucket that overwrote it would point the deploy at a
//      catalog it never fetches — and silently discard a good pin.
//
// The script is run for real against a stub wrangler, from a temp tree laid
// out the way it expects. It resolves its output from import.meta.url, so a
// copy in the temp tree writes there and this test never touches the repo.

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const WORKER = new URL('../../packages/worker/', import.meta.url).pathname;
const PIN_RE = /RUNTIME_CATALOG_SHA256: string = "([a-f0-9]*)"/;

// Formatted the way the publish path writes it, so the digest is over bytes
// of the same shape the real thing produces.
const CATALOG = JSON.stringify(
  { version: 1, runtimes: { python: { default: '1.0', versions: {} } } },
  null,
  2,
);
const CATALOG_SHA = createHash('sha256').update(CATALOG).digest('hex');

const root = mkdtempSync(join(tmpdir(), 'nimbus-pin-test-'));
try {
  mkdirSync(join(root, 'scripts'), { recursive: true });
  mkdirSync(join(root, 'src'), { recursive: true });
  mkdirSync(join(root, 'bin'), { recursive: true });
  cpSync(join(WORKER, 'scripts/bundle-runtime.mjs'), join(root, 'scripts/bundle-runtime.mjs'));
  cpSync(join(WORKER, 'runtime-contracts'), join(root, 'runtime-contracts'), { recursive: true });

  // Stub wrangler: `r2 object get <bucket>/<key> --file <path> --remote`.
  // Answers from the object store rather than the command line so a run
  // against a bucket that should not be read still shows up as a wrong digest.
  writeFileSync(
    join(root, 'bin/wrangler'),
    `#!/usr/bin/env node
const fs = require('node:fs');
const args = process.argv.slice(2);
const i = args.indexOf('--file');
if (args[0] === 'r2' && args[1] === 'object' && args[2] === 'get' && i > 0) {
  fs.writeFileSync(args[i + 1], ${JSON.stringify(CATALOG)});
  process.exit(0);
}
process.exit(1);
`,
    { mode: 0o755 },
  );

  const pinPath = join(root, 'src/runtime-catalog.generated.ts');
  const readPin = () => (existsSync(pinPath) ? PIN_RE.exec(readFileSync(pinPath, 'utf8'))?.[1] ?? null : null);

  const run = (...args) =>
    spawnSync(process.execPath, [join(root, 'scripts/bundle-runtime.mjs'), '--pin-catalog', ...args], {
      cwd: root, // no node_modules here, so WRANGLER falls back to PATH
      encoding: 'utf8',
      env: { ...process.env, PATH: `${join(root, 'bin')}:${process.env.PATH}`, CLOUDFLARE_ACCOUNT_ID: 'test-account' },
    });

  // ── An isolated bucket must not rewrite the production pin ────────────
  writeFileSync(pinPath, 'export const RUNTIME_CATALOG_SHA256: string = "";\n');
  const isolated = run('--bucket', 'nimbus-runtime-cache-some-experiment');

  assert.equal(isolated.status, 0, `--pin-catalog against an isolated bucket failed:\n${isolated.stderr}`);
  assert.equal(readPin(), '', 'a publish to an isolated bucket overwrote the production catalog pin');
  assert.match(isolated.stdout, /LEFT ALONE/, 'leaving the pin alone was not reported');

  // ── The production bucket pins the bytes it fetched ───────────────────
  const production = run();

  assert.equal(production.status, 0, `--pin-catalog failed:\n${production.stderr}`);
  assert.equal(
    readPin(),
    CATALOG_SHA,
    'the pin is not the digest of the catalog that was fetched, so the deploy would never hit L2',
  );

  // The generated file is a TypeScript module the worker imports; a pin that
  // does not parse would fail the build rather than the cache.
  const emitted = readFileSync(pinPath, 'utf8');
  assert.match(emitted, /^export const RUNTIME_CATALOG_SHA256: string = "[a-f0-9]{64}";$/m);
  assert.match(emitted, /AUTO-GENERATED by scripts\/bundle-runtime\.mjs/);

  // ── A bucket that cannot be read must not pin anything ────────────────
  writeFileSync(pinPath, 'export const RUNTIME_CATALOG_SHA256: string = "";\n');
  const broken = spawnSync(process.execPath, [join(root, 'scripts/bundle-runtime.mjs'), '--pin-catalog'], {
    cwd: root,
    encoding: 'utf8',
    // No stub on PATH: the fetch cannot succeed.
    env: { ...process.env, PATH: '/nonexistent', CLOUDFLARE_ACCOUNT_ID: 'test-account' },
  });
  assert.notEqual(broken.status, 0, 'a catalog that could not be read still exited 0');
  assert.equal(readPin(), '', 'a failed fetch rewrote the pin');
} finally {
  rmSync(root, { recursive: true, force: true });
}

console.log('bundle-runtime-catalog-pin: ok');
