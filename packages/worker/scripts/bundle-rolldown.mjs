#!/usr/bin/env node
/**
 * bundle-rolldown.mjs — stage the single-threaded rolldown binding for Nimbus.
 *
 * rolldown (Vite 8's bundler, also a direct dependency of Nuxt) loads a native
 * N-API binding; its only published wasm build targets wasm32-wasip1-threads,
 * which a Worker isolate cannot run. scripts/rolldown/build-binding.mjs builds
 * the same binding for plain wasm32-wasip1 from pinned upstream source and
 * writes an artifact directory:
 *
 *   rolldown-binding.wasm        the binding (upstream rolldown_binding + an
 *                                event-loop-driven async runtime)
 *   wasi-trampoline.wasm         sync/JSPI dispatch for filesystem imports
 *   rolldown-binding-loader.mjs  N-API (emnapi, non-threaded) + WASI loader
 *   provenance.json              inputs, toolchain, flags, output digests
 *
 * This script does NOT rebuild (that needs the pinned Rust toolchain and a
 * bounded 16 GB cgroup). It stages that directory into the static-assets
 * layer and pins every file's SHA-256 in src/rolldown-artifact.generated.ts,
 * which runtime/rolldown-artifact.ts verifies on every fetch:
 *
 *   public/_assets/rolldown/<version>/<file>
 *
 * Source dir: NIMBUS_ROLLDOWN_ARTIFACT, else the committed
 * public/_assets/rolldown/<version>/ (the artifact is tracked, so a checkout
 * without the Rust build re-derives the same generated module).
 *
 * Run via: node scripts/bundle-rolldown.mjs (wired into `bundle`).
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ASSETS_DIR = path.join(ROOT, 'public', '_assets', 'rolldown');
const OUT_TS = path.join(ROOT, 'src', 'rolldown-artifact.generated.ts');
/** Each staged file and the constant prefix its path, digest and size export under. */
const CONSTANT_PREFIX = {
  'rolldown-binding.wasm': 'ROLLDOWN_BINDING',
  'wasi-trampoline.wasm': 'ROLLDOWN_TRAMPOLINE',
  'rolldown-binding-loader.mjs': 'ROLLDOWN_LOADER',
  'provenance.json': 'ROLLDOWN_PROVENANCE',
};
const FILES = Object.keys(CONSTANT_PREFIX);

async function committedSource() {
  const versions = (await fs.readdir(ASSETS_DIR).catch(() => [])).filter((v) => !v.startsWith('.'));
  if (versions.length !== 1) {
    throw new Error(`[bundle-rolldown] expected one staged version under ${ASSETS_DIR}, found ${JSON.stringify(versions)}; set NIMBUS_ROLLDOWN_ARTIFACT`);
  }
  return path.join(ASSETS_DIR, versions[0]);
}

const sourceDir = process.env.NIMBUS_ROLLDOWN_ARTIFACT
  ? path.resolve(process.env.NIMBUS_ROLLDOWN_ARTIFACT)
  : await committedSource();
const provenance = JSON.parse(await fs.readFile(path.join(sourceDir, 'provenance.json'), 'utf8'));
const version = provenance.rolldownVersion;
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`[bundle-rolldown] provenance.json has no rolldownVersion`);
}

const digests = {};
const sizes = {};
const targetDir = path.join(ASSETS_DIR, version);
for (const file of FILES) {
  const bytes = await fs.readFile(path.join(sourceDir, file));
  digests[file] = createHash('sha256').update(bytes).digest('hex');
  sizes[file] = bytes.length;
  const recorded = provenance.outputs[file]?.sha256;
  if (file !== 'provenance.json' && recorded !== digests[file]) {
    throw new Error(`[bundle-rolldown] ${file} sha256 ${digests[file]} does not match provenance.json (${recorded})`);
  }
}
if (sourceDir !== targetDir) {
  for (const entry of await fs.readdir(ASSETS_DIR).catch(() => [])) {
    if (entry !== version) await fs.rm(path.join(ASSETS_DIR, entry), { recursive: true, force: true });
  }
  await fs.mkdir(targetDir, { recursive: true });
  for (const file of FILES) await fs.copyFile(path.join(sourceDir, file), path.join(targetDir, file));
}
const buildId = createHash('sha256').update(JSON.stringify(digests)).digest('hex').slice(0, 16);

const ts = `/**
 * rolldown-artifact.generated.ts — AUTO-GENERATED by scripts/bundle-rolldown.mjs
 * DO NOT EDIT.
 *
 * The single-threaded wasm32-wasip1 build of rolldown ${version}'s N-API
 * binding (scripts/rolldown/build-binding.mjs), staged under
 * public/_assets/rolldown/${version}/. PACKAGE_ABI_POLICY.stagedArtifacts maps
 * \`rolldown\` and \`@rolldown/binding-wasm32-wasi\` to it; runtime/
 * rolldown-artifact.ts fetches each file and verifies it against the digest
 * below before it is compiled or evaluated.
 */

export const ROLLDOWN_ARTIFACT_VERSION: string = ${JSON.stringify(version)};
export const ROLLDOWN_ARTIFACT_BUILD_ID: string = ${JSON.stringify(buildId)};
${Object.entries(CONSTANT_PREFIX).map(([file, prefix]) => `
export const ${prefix}_PATH: string = ${JSON.stringify(`/_assets/rolldown/${version}/${file}`)};
export const ${prefix}_SHA256: string = ${JSON.stringify(digests[file])};
export const ${prefix}_BYTES: number = ${sizes[file]};`).join('\n')}
`;
await fs.writeFile(OUT_TS, ts);
console.log(`[bundle-rolldown] staged rolldown ${version} binding (${buildId}) -> ${path.relative(ROOT, targetDir)}`);
