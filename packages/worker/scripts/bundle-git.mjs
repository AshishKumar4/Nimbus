#!/usr/bin/env node
/**
 * bundle-git.mjs — Build the patched git module for hosts and network facets.
 *
 * WHY this exists:
 *   The git-network-facet runs inside a dynamic worker loaded via
 *   env.LOADER.load(). Dynamic workers have NO access to node_modules —
 *   they only see modules explicitly passed in the `modules` object.
 *
 *   Hosts import the executable module shipped in vendor/. Consumers never
 *   depend on Nimbus' repository postinstall having patched their dependencies.
 *
 *   This script bundles isomorphic-git + isomorphic-git/http/web into ONE
 *   ESM module. The same bytes become the string required by LOADER.load().
 *
 * Output:
 *   vendor/git.generated.mjs + self-contained declarations
 *   src/git-bundle.generated.ts — exports GIT_BUNDLE_CODE: string
 *
 * Runs as a postinstall step AND on every `bun run dev` / `bun run deploy`
 * via the "bundle:git" npm script.
 */

import { build } from 'esbuild';
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

import { assertCfGitPatched } from './cf-git-patch.mjs';
import { resolvePackageDir } from './resolve-package-dir.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// Entry that aggregates both namespaces into a single ESM bundle.
const ENTRY_CONTENTS = [
  "export * as git from 'isomorphic-git';",
  "export * as gitHttp from 'isomorphic-git/http/web';",
].join('\n');

const ENTRY_FILE = join(root, '.git-bundle-entry.js');

// Upstream declarations are copied mechanically; only the tracked patch's
// public signature changes live here. No consumer dependency on the build input.
const GIT_TYPES = `import type * as Upstream from './git-upstream.generated.js';
type Add = Parameters<typeof Upstream.add>[0];
type Remove = Parameters<typeof Upstream.remove>[0];
type Commit = Parameters<typeof Upstream.commit>[0];
type Matrix = Parameters<typeof Upstream.statusMatrix>[0];
type Checkout = Parameters<typeof Upstream.checkout>[0];
export declare const git: Omit<typeof Upstream, 'add' | 'remove' | 'commit' | 'statusMatrix'> & {
  add(options: Omit<Add, 'filepath'> & { filepath: string | string[] }): ReturnType<typeof Upstream.add>;
  remove(options: Omit<Remove, 'filepath'> & { filepath: string | string[] }): ReturnType<typeof Upstream.remove>;
  commit(options: Commit & { rawMessage?: boolean }): ReturnType<typeof Upstream.commit>;
  statusMatrix(options: Matrix & { deferRefresh?: boolean }): ReturnType<typeof Upstream.statusMatrix>;
  stage(options: Pick<Add, 'fs' | 'dir' | 'gitdir' | 'cache' | 'force' | 'parallel'> & {
    add?: string[]; remove?: string[];
  }): Promise<void>;
  checkoutFreshChunk(options: Pick<Checkout, 'fs' | 'dir' | 'gitdir' | 'ref' | 'cache' | 'onProgress'> & {
    cursor?: object | null; maxEntries: number; maxDecodedBytes: number; maxWallMs: number;
    deferIndexFragmentCleanup?: boolean;
  }): Promise<{ nextCursor: object | null; files: number; decodedBytes: number; treeEntriesVisited: number; indexEntries: number }>;
};
export { default as gitHttp } from './git-http.generated.js';
`;

function declaration(source, destination) {
  const text = readFileSync(source, 'utf8');
  if (ts.preProcessFile(text).importedFiles.length) {
    throw new Error('Git declarations acquired imports; bundle their types before publishing: ' + source);
  }
  writeFileSync(destination, '// Generated by scripts/bundle-git.mjs from the pinned cf-git declarations.\n' + text);
}

async function main() {
  // A copy patched by another revision of the tracked patch would bundle
  // without its fixes, and nothing downstream would notice: refuse instead.
  const gitDir = resolvePackageDir('isomorphic-git', { start: root });
  assertCfGitPatched(join(root, '..', '..'), [gitDir]);
  try {
    writeFileSync(ENTRY_FILE, ENTRY_CONTENTS);

    const result = await build({
      entryPoints: [ENTRY_FILE],
      bundle: true,
      format: 'esm',
      target: 'esnext',
      platform: 'browser',
      absWorkingDir: root,
      conditions: ['worker', 'browser', 'import'],
      // Map bare node built-ins → node: prefixed (works with nodejs_compat).
      alias: {
        crypto: 'node:crypto',
      },
      // Anything else that might leak: leave as external. nodejs_compat
      // provides these at runtime in the dynamic worker.
      external: [
        'node:*',
        'cloudflare:workers',
      ],
      // The bundle ships as a string inside the supervisor Worker, which has a
      // size budget (tests/behavioral/assets-fetch/new/worker-bundle-size.mjs).
      // Whitespace and syntax minification take ~200 KB off it; identifiers
      // are kept, so stack traces from the facet still name cf-git's functions.
      minifyWhitespace: true,
      minifySyntax: true,
      write: false,
      logLevel: 'warning',
    });

    if (!result.outputFiles || result.outputFiles.length === 0) {
      throw new Error('esbuild produced no output');
    }

    const code = result.outputFiles[0].text;

    const vendor = join(root, 'vendor');
    mkdirSync(vendor, { recursive: true });
    writeFileSync(join(vendor, 'git.generated.mjs'), code);
    writeFileSync(join(vendor, 'git.LICENSE'), readFileSync(join(gitDir, 'LICENSE.md')));
    declaration(join(gitDir, 'index.d.ts'), join(vendor, 'git-upstream.generated.d.ts'));
    declaration(join(gitDir, 'http', 'web', 'index.d.ts'), join(vendor, 'git-http.generated.d.ts'));
    writeFileSync(join(vendor, 'git.generated.d.mts'), '// Generated by scripts/bundle-git.mjs.\n' + GIT_TYPES);

    // Emit as a TS module that exports the bundle as a string constant.
    // Using String.raw-equivalent: JSON-encode to preserve backticks/$/etc.
    const outPath = join(root, 'src', 'git-bundle.generated.ts');

    // We JSON.stringify the code to produce a valid JS string literal.
    // Then wrap in a TS const export. The supervisor imports this at build.
    const encoded = JSON.stringify(code);

    const tsWrapper = [
      '/**',
      ' * git-bundle.generated.ts — AUTO-GENERATED. DO NOT EDIT.',
      ' *',
      ' * Produced by scripts/bundle-git.mjs from:',
      " *   - isomorphic-git (github:AshishKumar4/cf-git)",
      " *   - isomorphic-git/http/web",
      ' *',
      ' * Consumed by git-network-facet.ts: passed to LOADER.load()\'s',
      ' * `modules` record so the facet can `import` isomorphic-git.',
      ' *',
      ` * Size: ${(code.length / 1024).toFixed(1)} KiB`,
      ' */',
      '',
      `export const GIT_BUNDLE_CODE: string = ${encoded};`,
      '',
      `export const GIT_BUNDLE_SIZE = ${code.length};`,
      '',
    ].join('\n');

    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, tsWrapper);

    console.log(`[bundle-git] wrote ${outPath} (${(code.length / 1024).toFixed(1)} KiB bundled)`);
  } finally {
    // Clean up the temp entry file
    try {
      if (existsSync(ENTRY_FILE)) {
        const { unlinkSync } = await import('node:fs');
        unlinkSync(ENTRY_FILE);
      }
    } catch {}
  }
}

main().catch((e) => {
  console.error('[bundle-git] FAILED:', e?.message || e);
  process.exitCode = 1;
});
