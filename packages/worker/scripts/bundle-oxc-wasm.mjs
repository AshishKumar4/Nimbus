#!/usr/bin/env node
/**
 * bundle-oxc-wasm.mjs — stage Nimbus's Oxc transform for the transform facet.
 *
 * scripts/oxc-wasm/build.mjs builds the crate in scripts/oxc-wasm into
 *
 *   nimbus-oxc.wasm, provenance.json
 *
 * This script does NOT rebuild (that needs the pinned Rust toolchain), and
 * refuses a wasm whose provenance records other inputs than the tree's
 * (scripts/oxc-wasm/inputs.mjs: the crate, its lockfile and toolchain pin,
 * the recipe and its compiler wrapper), so a Rust change cannot ship the
 * previous build. It stages that pair into the static-assets layer under a name carrying a
 * prefix of the wasm's digest, so no cache layer can serve another build's
 * bytes under it, and pins the digest and size in
 * src/oxc-wasm-artifact.generated.ts, which runtime/oxc-wasm-bytes.ts verifies
 * on every fetch:
 *
 *   public/_assets/oxc/nimbus-oxc-<build id>.wasm
 *   public/_assets/oxc/nimbus-oxc-<build id>.provenance.json
 *
 * Source: NIMBUS_OXC_WASM_ARTIFACTS (a build.mjs --out directory), else the
 * committed public/_assets/oxc/ (the artifact is tracked, so a checkout
 * without the Rust build re-derives the same generated module).
 *
 * Run via: node scripts/bundle-oxc-wasm.mjs (wired into `bundle`).
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { changedInputs, oxcWasmInputs } from './oxc-wasm/inputs.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ASSETS = path.join(ROOT, 'public', '_assets', 'oxc');
const OUT_TS = path.join(ROOT, 'src', 'oxc-wasm-artifact.generated.ts');

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const fail = (message) => { throw new Error(`[bundle-oxc-wasm] ${message}`); };

/** The wasm and its provenance: a fresh build's, or the committed stage's. */
async function source() {
  const built = process.env.NIMBUS_OXC_WASM_ARTIFACTS;
  if (built) {
    const dir = path.resolve(built);
    return { wasm: path.join(dir, 'nimbus-oxc.wasm'), provenance: path.join(dir, 'provenance.json') };
  }
  const staged = (await fs.readdir(ASSETS).catch(() => [])).filter((e) => e.endsWith('.wasm'));
  if (staged.length !== 1) fail(`expected one staged wasm under ${ASSETS}, found ${JSON.stringify(staged)}; set NIMBUS_OXC_WASM_ARTIFACTS`);
  const wasm = path.join(ASSETS, staged[0]);
  return { wasm, provenance: wasm.replace(/\.wasm$/, '.provenance.json') };
}

const src = await source();
const wasm = await fs.readFile(src.wasm);
const provenanceText = await fs.readFile(src.provenance, 'utf8');
const provenance = JSON.parse(provenanceText);
const digest = sha256(wasm);
if (provenance.artifact !== 'nimbus-oxc') fail(`${src.provenance} describes ${provenance.artifact}, not nimbus-oxc`);
if (provenance.outputs?.['nimbus-oxc.wasm']?.sha256 !== digest) {
  fail(`${src.wasm} sha256 ${digest} does not match its provenance.json (${provenance.outputs?.['nimbus-oxc.wasm']?.sha256})`);
}
const stale = changedInputs(provenance.source?.inputs, await oxcWasmInputs());
if (stale.length) {
  fail(`${src.wasm} was built from other inputs than this tree's (${stale.join(', ')}); rebuild it with scripts/oxc-wasm/build.mjs and stage that build`);
}
const memoryPages = provenance.wasm?.memoryInitialPages;
if (!Number.isInteger(memoryPages) || memoryPages <= 0) fail(`${src.provenance} records no memoryInitialPages`);

const buildId = digest.slice(0, 16);
const wasmName = `nimbus-oxc-${buildId}.wasm`;
const provenanceName = `nimbus-oxc-${buildId}.provenance.json`;
await fs.mkdir(ASSETS, { recursive: true });
for (const entry of await fs.readdir(ASSETS)) {
  if (entry !== wasmName && entry !== provenanceName) await fs.rm(path.join(ASSETS, entry), { recursive: true, force: true });
}
if (path.resolve(src.wasm) !== path.join(ASSETS, wasmName)) {
  await fs.writeFile(path.join(ASSETS, wasmName), wasm);
  await fs.writeFile(path.join(ASSETS, provenanceName), provenanceText);
}

await fs.writeFile(OUT_TS, `/**
 * oxc-wasm-artifact.generated.ts — AUTO-GENERATED by scripts/bundle-oxc-wasm.mjs
 * DO NOT EDIT.
 *
 * Nimbus's Oxc transform (scripts/oxc-wasm, built by its build.mjs; inputs in
 * the staged provenance.json), staged under public/_assets/oxc/. The transform
 * facet's builder (runtime/oxc-wasm-bytes.ts) fetches it and verifies it
 * against OXC_WASM_SHA256 before the loader compiles it. The module imports
 * nothing; its memory starts at OXC_WASM_MEMORY_PAGES pages (stack and static
 * data) and grows only while a transform runs.
 *
 * oxc ${provenance.oxc}, ${provenance.toolchain.split('\n')[0]}, ${(wasm.length / 1048576).toFixed(2)} MiB
 */

export const OXC_VERSION: string = ${JSON.stringify(provenance.oxc)};
export const OXC_WASM_ASSET_PATH: string = ${JSON.stringify(`/_assets/oxc/${wasmName}`)};
export const OXC_WASM_BUILD_ID: string = ${JSON.stringify(buildId)};
export const OXC_WASM_SHA256: string = ${JSON.stringify(digest)};
export const OXC_WASM_BYTES: number = ${wasm.length};
export const OXC_WASM_MEMORY_PAGES: number = ${memoryPages};
`);
console.log(`[bundle-oxc-wasm] staged /_assets/oxc/${wasmName} (${wasm.length} bytes, sha256 ${digest})`);
