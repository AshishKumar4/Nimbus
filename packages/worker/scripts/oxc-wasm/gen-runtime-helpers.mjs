#!/usr/bin/env node
/**
 * gen-runtime-helpers.mjs — write src/runtime_helpers.rs: the helpers of
 * @oxc-project/runtime that Oxc's transformer imports for TypeScript's legacy
 * decorators and for class fields lowered to assignments (and what they
 * import), verbatim from the package, which lib.rs inlines into a
 * transform's output (a transform's output has no runtime package to import
 * them from).
 *
 *   node scripts/oxc-wasm/gen-runtime-helpers.mjs <unpacked @oxc-project/runtime package>
 *
 * The package's version must be the crate's oxc version (Cargo.toml).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CRATE = path.dirname(fileURLToPath(import.meta.url));
const pkg = process.argv[2];
if (!pkg) throw new Error('usage: gen-runtime-helpers.mjs <unpacked @oxc-project/runtime package>');
const { version } = JSON.parse(readFileSync(path.join(pkg, 'package.json'), 'utf8'));
const oxc = /^oxc = \{ version = "=?([^"]+)"/m.exec(readFileSync(path.join(CRATE, 'Cargo.toml'), 'utf8'))?.[1];
if (version !== oxc) throw new Error(`@oxc-project/runtime ${version} is not the crate's oxc ${oxc}`);

// What oxc_transformer's legacy decorator and class-properties transforms request (Helper::name).
const ROOTS = [
  'decorate', 'decorateParam', 'decorateMetadata', 'classPrivateFieldInitSpec', 'classPrivateFieldGet2', 'classPrivateFieldSet2',
  'classPrivateMethodInitSpec', 'assertClassBrand', 'defineProperty', 'superPropGet', 'superPropSet', 'toSetter', 'readOnlyError',
  'writeOnlyError', 'checkInRHS', 'classPrivateFieldLooseKey', 'classPrivateFieldLooseBase',
];
const sources = new Map();
const visit = (name) => {
  if (sources.has(name)) return;
  const text = readFileSync(path.join(pkg, 'src', 'helpers', 'esm', `${name}.js`), 'utf8');
  if (!/^export \{ \w+ as default \};$/m.test(text)) throw new Error(`${name}: no default export of the expected shape`);
  sources.set(name, text);
  for (const m of text.matchAll(/^import \w+ from "\.\/(\w+)\.js";$/gm)) visit(m[1]);
};
ROOTS.forEach(visit);

const entries = [...sources].sort(([a], [b]) => a.localeCompare(b)).map(([name, text]) => {
  if (text.includes('"#')) throw new Error(`${name}: contains "#`);
  return `    ("${name}", r#"${text}"#),`;
});
writeFileSync(path.join(CRATE, 'src', 'runtime_helpers.rs'), `//! @oxc-project/runtime ${version}'s helpers that Oxc's transformer imports for
//! TypeScript's legacy decorators and for class fields lowered to assignments,
//! and what they import: each its ES module, verbatim. lib.rs inlines them into
//! a transform's output. GENERATED by scripts/oxc-wasm/gen-runtime-helpers.mjs
//! from the npm package; do not edit.
//!
//! @oxc-project/runtime: MIT License, Copyright (c) 2024-present VoidZero Inc.
//! & Contributors. Its helpers are Babel's (MIT), and \`decorate\`,
//! \`decorateParam\` and \`decorateMetadata\` TypeScript's emit helpers
//! (Apache-2.0, Copyright (c) Microsoft Corporation).

/// (name, ES module source), by name.
pub const HELPERS: &[(&str, &str)] = &[
${entries.join('\n')}
];
`);
console.log(`[gen-runtime-helpers] ${sources.size} helpers from @oxc-project/runtime ${version}`);
