#!/usr/bin/env node
// Stages amaro's inline wasm as public/_assets/amaro/amaro-<build id>.wasm,
// pinned (and verified on fetch) by src/amaro-wasm-artifact.generated.ts.

import { promises as fs } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256Hex as sha256 } from './stage-asset.mjs';
import { amaroInlineWasm } from './amaro-driver.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ASSETS = path.join(ROOT, 'public', '_assets', 'amaro');
const OUT_TS = path.join(ROOT, 'src', 'amaro-wasm-artifact.generated.ts');

const CORE = path.resolve(ROOT, '..', 'core');
const require = createRequire(path.join(CORE, 'package.json'));
const entry = require.resolve('amaro');
// amaro's exports leave out its package.json; its entry is dist/index.js.
const pkg = JSON.parse(await fs.readFile(path.resolve(path.dirname(entry), '..', 'package.json'), 'utf8'));
const pinned = JSON.parse(await fs.readFile(path.join(CORE, 'package.json'), 'utf8')).devDependencies.amaro;
if (pkg.version !== pinned) throw new Error(`[bundle-amaro-wasm] the installed amaro is ${pkg.version}, the pin ${pinned}`);
const wasm = amaroInlineWasm(await fs.readFile(entry, 'utf8'));
const digest = sha256(wasm);
const buildId = digest.slice(0, 16);
const wasmName = `amaro-${buildId}.wasm`;
await fs.mkdir(ASSETS, { recursive: true });
for (const entry of await fs.readdir(ASSETS)) {
  if (entry !== wasmName) await fs.rm(path.join(ASSETS, entry), { recursive: true, force: true });
}
await fs.writeFile(path.join(ASSETS, wasmName), wasm);

await fs.writeFile(OUT_TS, `// AUTO-GENERATED by scripts/bundle-amaro-wasm.mjs. DO NOT EDIT.

export const AMARO_VERSION: string = ${JSON.stringify(pkg.version)};
export const AMARO_WASM_ASSET_PATH: string = ${JSON.stringify(`/_assets/amaro/${wasmName}`)};
export const AMARO_WASM_BUILD_ID: string = ${JSON.stringify(buildId)};
export const AMARO_WASM_SHA256: string = ${JSON.stringify(digest)};
export const AMARO_WASM_BYTES: number = ${wasm.length};
`);
console.log(`[bundle-amaro-wasm] staged /_assets/amaro/${wasmName} (${wasm.length} bytes, sha256 ${digest})`);
