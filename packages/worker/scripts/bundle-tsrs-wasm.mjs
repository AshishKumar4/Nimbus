#!/usr/bin/env node
// Stages tsrs.wasm, from the pinned @tsrs/wasm (a devDependency at an exact
// version), as public/_assets/tsrs/tsrs-<build id>.wasm, pinned (and verified
// on fetch) by src/tsrs-wasm-artifact.generated.ts. The bytes must be the
// ones this script names: a package that installs other bytes under the
// pinned version is refused.

import { promises as fs } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sha256Hex as sha256, stageAsset } from './stage-asset.mjs';

/** tsrs.wasm of @tsrs/wasm 0.18.0-ts7.1.0-dev.20260929 (npm integrity sha512-1Wv0GU3O…). */
const PINNED_SHA256 = 'bb070f1416dccc5956d177f527b81534a86032efd4d94898dfc20aae1a5c4d18';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ASSETS = path.join(ROOT, 'public', '_assets', 'tsrs');
const OUT_TS = path.join(ROOT, 'src', 'tsrs-wasm-artifact.generated.ts');

const require = createRequire(path.join(ROOT, 'package.json'));
const manifestPath = require.resolve('@tsrs/wasm/package.json');
const pkg = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
const pinned = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8')).devDependencies['@tsrs/wasm'];
if (pkg.version !== pinned) throw new Error(`[bundle-tsrs-wasm] the installed @tsrs/wasm is ${pkg.version}, the pin ${pinned}`);
// `<tsrs version>-ts<the TypeScript version it ports>`, as the package names itself.
const versions = /^(\d+\.\d+\.\d+)-ts(.+)$/.exec(pkg.version);
if (!versions) throw new Error(`[bundle-tsrs-wasm] @tsrs/wasm ${pkg.version} does not name the TypeScript it ports`);
const wasm = await fs.readFile(path.join(path.dirname(manifestPath), 'tsrs.wasm'));
const digest = sha256(wasm);
if (digest !== PINNED_SHA256) throw new Error(`[bundle-tsrs-wasm] @tsrs/wasm ${pkg.version}'s tsrs.wasm is sha256 ${digest}, the pin ${PINNED_SHA256}`);
const buildId = digest.slice(0, 16);
const wasmName = `tsrs-${buildId}.wasm`;
stageAsset(ASSETS, wasmName, wasm, (entry) => entry.startsWith('tsrs-'));

await fs.writeFile(OUT_TS, `// AUTO-GENERATED by scripts/bundle-tsrs-wasm.mjs. DO NOT EDIT.

/** tsrs, the Rust port of the TypeScript compiler, and the TypeScript version it ports. */
export const TSRS_VERSION: string = ${JSON.stringify(versions[1])};
export const TSRS_TYPESCRIPT_VERSION: string = ${JSON.stringify(versions[2])};
export const TSRS_WASM_ASSET_PATH: string = ${JSON.stringify(`/_assets/tsrs/${wasmName}`)};
export const TSRS_WASM_SHA256: string = ${JSON.stringify(digest)};
export const TSRS_WASM_BYTES: number = ${wasm.length};
`);
console.log(`[bundle-tsrs-wasm] staged /_assets/tsrs/${wasmName} (${wasm.length} bytes, sha256 ${digest})`);
