#!/usr/bin/env node
/**
 * pin-transform-pipeline.mjs — part of core's build: pins the launch
 * transform pipeline's code identity in src/runtime/transform-pipeline.generated.ts.
 *
 * A session keeps its launch transform results by content (worker
 * facets/transform-store.ts), each under the sha256 of, among other things,
 * TRANSFORM_PIPELINE_ID: the sha256 of the bundled closure of
 * src/runtime/bundle-cell-transform.ts and EsbuildService — every step that
 * decides a cell's output in the session, tree-shaken to what those reach,
 * acorn included. The closure is hashed minified, so what moves the id is
 * code: an edit to a comment or a layout keeps every stored result. The id
 * is generated here, in core's own build, so it ships
 * in core's dist with the code it describes: an embedder that upgrades only
 * core gets the new pipeline's id with the new pipeline, and never a result
 * the old one stored.
 *
 * esbuild-wasm stays out: only an in-isolate esbuild loads it, and nothing
 * stores that one's results; the esbuild facet's version is part of the
 * transform host's identity instead. The generated file is not in the closure
 * (nothing in it imports the id), or the id would be a hash of itself.
 */

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const coreRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const runtimeDir = join(coreRoot, 'src', 'runtime');
export const TRANSFORM_PIPELINE_GENERATED = join(runtimeDir, 'transform-pipeline.generated.ts');

/**
 * The pipeline's bundled closure. `plugins` are added to the build as given;
 * the parity test uses one to show that a change to any reachable source
 * changes the id.
 */
export async function bundleTransformPipeline({ plugins = [] } = {}) {
  const result = await build({
    stdin: {
      contents: "export * from './bundle-cell-transform.ts';\nexport { EsbuildService } from './esbuild-service.ts';\n",
      resolveDir: runtimeDir,
      sourcefile: 'transform-pipeline.ts',
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    target: 'esnext',
    platform: 'neutral',
    absWorkingDir: coreRoot,
    external: ['esbuild-wasm', 'esbuild-wasm/*'],
    plugins,
    minify: true,
    write: false,
    logLevel: 'warning',
    legalComments: 'none',
  });
  const text = result.outputFiles?.[0]?.text ?? '';
  const exported = text.match(/export\s*\{([^}]*)\}\s*;?\s*$/)?.[1] ?? '';
  if (!/\btransformBundleCells\b/.test(exported) || !/\bEsbuildService\b/.test(exported)) {
    throw new Error('[pin-transform-pipeline] the pipeline bundle lost transformBundleCells or EsbuildService');
  }
  return text;
}

/** TRANSFORM_PIPELINE_ID for the pipeline as `plugins` leave it. */
export async function transformPipelineId(options) {
  return createHash('sha256').update(await bundleTransformPipeline(options), 'utf8').digest('hex');
}

async function main() {
  const text = await bundleTransformPipeline();
  const id = createHash('sha256').update(text, 'utf8').digest('hex');
  writeFileSync(TRANSFORM_PIPELINE_GENERATED, [
    '/**',
    ' * transform-pipeline.generated.ts — AUTO-GENERATED by',
    ' * scripts/pin-transform-pipeline.mjs (core\'s build). DO NOT EDIT.',
    ' *',
    ' * The launch transform pipeline\'s code identity: the sha256 of the bundled',
    ' * closure of runtime/bundle-cell-transform.ts and EsbuildService. The',
    ' * worker\'s transform store keys every stored result by it, so no build',
    ' * serves a result another build\'s pipeline produced.',
    ' *',
    ` * Closure: ${(text.length / 1024).toFixed(2)} KiB`,
    ' */',
    '',
    `export const TRANSFORM_PIPELINE_ID: string = ${JSON.stringify(id)};`,
    '',
  ].join('\n'));
  console.log(`[pin-transform-pipeline] ${id} (closure ${(text.length / 1024).toFixed(2)} KiB)`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch((error) => {
    console.error('[pin-transform-pipeline] FAILED:', error?.message || error);
    process.exitCode = 1;
  });
}
