#!/usr/bin/env node
// Writes src/runtime/node-cli-options.generated.ts: Node's own command-line
// option table, as the node running this script holds it (internal/options):
// what each option takes, which NODE_OPTIONS may carry, and the aliases. Run
//   node --expose-internals packages/core/scripts/gen-node-cli-options.mjs
// under the release Nimbus's node answers as (core/src/constants.ts
// NODE_VERSIONS); under any other it refuses, rather than write another
// release's table. With --json it prints the table instead of writing it
// (tests/unit/node-cli-matches-node.mjs compares the two).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { NODE_VERSION } from '../src/constants.ts';

if (process.version !== NODE_VERSION) {
  console.error(`gen-node-cli-options: this is Node ${process.version}, and Nimbus's node is ${NODE_VERSION} `
    + '(core/src/constants.ts NODE_VERSIONS): run it under that release, or move the pin there first.');
  process.exit(1);
}

const require = createRequire(import.meta.url);
/**
 * Node's own option table: a module of Node's internals, there only under
 * --expose-internals, so it is named at run time, not resolved as a package.
 * @typedef {{ options: Map<string, { type: number, envVarSettings: number }>, aliases: Map<string, string[]> }} CLIOptionsInfo
 */
const INTERNAL_OPTIONS = 'internal/options';
/** @type {{ getCLIOptionsInfo(): CLIOptionsInfo }} */
const { getCLIOptionsInfo } = require(INTERNAL_OPTIONS);
const { options, aliases } = getCLIOptionsInfo();
// Copied first: process.allowedNodeEnvironmentFlags' getter
// (lib/internal/process/per_thread.js isAccepted) splices an alias's own name
// out of this same table, which made `--prof-process` stand for `--` alone.
// Nothing here reads that getter; NODE_OPTIONS' options are each option's own
// envVarSettings, as OptionsParser::Parse checks them.
const aliasEntries = [...aliases].map(([alias, expansion]) => [alias, [...expansion]]).sort(([a], [b]) => (a < b ? -1 : 1));
// node_options.h OptionType: kNoOp 0, kV8Option 1, kBoolean 2; the rest
// (kInteger, kUInteger, kString, kHostPort, kStringList) take a value.
const KINDS = new Map([[0, 'noop'], [1, 'v8'], [2, 'boolean']]);
// EnvironmentOptions' kAllowedInEnvvar.
const ALLOWED_IN_ENVVAR = 0;
/** @type {[string, { kind: string, env: boolean }][]} */
const table = [...options]
  .map(([name, info]) => /** @type {[string, { kind: string, env: boolean }]} */ ([name, { kind: KINDS.get(info.type) ?? 'value', env: info.envVarSettings === ALLOWED_IN_ENVVAR }]))
  .sort(([a], [b]) => (a < b ? -1 : 1));
// V8's own flags, which Node passes to V8 (an option neither knows is "bad"):
// each named as `node --v8-options` lists it.
const v8Flags = [...new Set(execFileSync(process.execPath, ['--v8-options'], { encoding: 'utf8' })
  .split('\n').flatMap((line) => /^ {2}--([a-z0-9][a-z0-9_-]*) /.exec(line)?.[1] ?? []))].sort();

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ version: process.version, options: table, v8Flags, aliases: aliasEntries }));
  process.exit(0);
}

const text = `// Generated by packages/core/scripts/gen-node-cli-options.mjs from Node ${process.version}'s
// own option table (internal/options). Do not edit.

/** How Node reads one of its options (node_options.h OptionType): \`value\` takes one; \`v8\` is passed to V8. */
export type NodeOptionKind = 'noop' | 'v8' | 'boolean' | 'value';

/** Node's options by canonical name: what each takes, and whether NODE_OPTIONS may carry it. */
export const NODE_OPTIONS_TABLE: ReadonlyMap<string, { readonly kind: NodeOptionKind; readonly env: boolean }> = new Map([
${table.map(([name, info]) => `  [${JSON.stringify(name)}, { kind: ${JSON.stringify(info.kind)}, env: ${info.env} }],`).join('\n')}
]);

/** V8's flags, without their dashes (V8 takes \`-\` and \`_\` alike in them). */
export const NODE_V8_FLAGS: ReadonlySet<string> = new Set([
${v8Flags.map((flag) => `  ${JSON.stringify(flag)},`).join('\n')}
]);

/** Each alias and what it stands for. */
export const NODE_OPTION_ALIASES: ReadonlyMap<string, readonly string[]> = new Map([
${aliasEntries.map(([alias, expansion]) => `  [${JSON.stringify(alias)}, ${JSON.stringify(expansion)}],`).join('\n')}
]);
`;
writeFileSync(new URL('../src/runtime/node-cli-options.generated.ts', import.meta.url), text);
const count = (kind) => table.filter(([, info]) => info.kind === kind).length;
console.log(`node-cli-options: ${table.length} options (${count('value')} take a value, ${count('boolean')} boolean, `
  + `${count('v8')} V8's, ${table.filter(([, info]) => info.env).length} allowed in NODE_OPTIONS), `
  + `${v8Flags.length} V8 flags, ${aliasEntries.length} aliases (Node ${process.version})`);
