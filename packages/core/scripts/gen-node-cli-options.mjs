#!/usr/bin/env node
// Writes src/runtime/node-cli-options.generated.ts: Node's own command-line
// option table, as the node running this script holds it (internal/options):
// which options take a value, which are allowed in NODE_OPTIONS
// (process.allowedNodeEnvironmentFlags), and the aliases. Run with
//   node --expose-internals packages/core/scripts/gen-node-cli-options.mjs
// under the Node release Nimbus's node answers as (22).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
/**
 * Node's own option table: a module of Node's internals, there only under
 * --expose-internals, so it is named at run time, not resolved as a package.
 * @typedef {{ options: Map<string, { type: number }>, aliases: Map<string, string[]> }} CLIOptionsInfo
 */
const INTERNAL_OPTIONS = 'internal/options';
/** @type {{ getCLIOptionsInfo(): CLIOptionsInfo }} */
const { getCLIOptionsInfo } = require(INTERNAL_OPTIONS);
const { options, aliases } = getCLIOptionsInfo();
// node_options.h OptionType: kInteger 3, kUInteger 4, kString 5, kHostPort 6, kStringList 7 take a value.
const VALUE_TYPES = new Set([3, 4, 5, 6, 7]);
const takesValue = [...options].filter(([, info]) => VALUE_TYPES.has(info.type)).map(([name]) => name).sort();
const known = [...options.keys()].sort();
// V8's own flags, which Node passes to V8 (an option neither knows is "bad"):
// each named as \`node --v8-options\` lists it.
const v8Flags = [...new Set(execFileSync(process.execPath, ['--v8-options'], { encoding: 'utf8' })
  .split('\n').flatMap((line) => /^ {2}--([a-z0-9][a-z0-9_-]*) /.exec(line)?.[1] ?? []))].sort();
// kBoolean 2: the options a --no- prefix may negate.
const booleans = [...options].filter(([, info]) => info.type === 2).map(([name]) => name).sort();
const allowedInEnv = [...process.allowedNodeEnvironmentFlags].sort();
const aliasEntries = [...aliases].map(([alias, expansion]) => [alias, [...expansion]]).sort(([a], [b]) => (a < b ? -1 : 1));
const list = (items) => items.map((item) => `  ${JSON.stringify(item)},`).join('\n');
const text = `// Generated by packages/core/scripts/gen-node-cli-options.mjs from Node ${process.version}'s
// own option table (internal/options, process.allowedNodeEnvironmentFlags). Do not edit.

/** The options that take a value (\`--name=value\`, or the next argument). */
export const NODE_VALUE_OPTIONS: ReadonlySet<string> = new Set([
${list(takesValue)}
]);

/** Every option Node's own table knows, by its canonical name. */
export const NODE_KNOWN_OPTIONS: ReadonlySet<string> = new Set([
${list(known)}
]);

/** V8's flags, without their dashes (V8 takes \`-\` and \`_\` alike in them). */
export const NODE_V8_FLAGS: ReadonlySet<string> = new Set([
${list(v8Flags)}
]);

/** The boolean options: the only ones \`--no-<name>\` negates. */
export const NODE_BOOLEAN_OPTIONS: ReadonlySet<string> = new Set([
${list(booleans)}
]);

/** The options NODE_OPTIONS may carry, aliases included. */
export const NODE_ENV_OPTIONS: ReadonlySet<string> = new Set([
${list(allowedInEnv)}
]);

/** Each alias and what it stands for. */
export const NODE_OPTION_ALIASES: ReadonlyMap<string, readonly string[]> = new Map([
${aliasEntries.map(([alias, expansion]) => `  [${JSON.stringify(alias)}, ${JSON.stringify(expansion)}],`).join('\n')}
]);
`;
writeFileSync(new URL('../src/runtime/node-cli-options.generated.ts', import.meta.url), text);
console.log(`node-cli-options: ${known.length} options, ${v8Flags.length} V8 flags, ${takesValue.length} value options, ${booleans.length} boolean options, ${allowedInEnv.length} NODE_OPTIONS options, ${aliasEntries.length} aliases (Node ${process.version})`);
