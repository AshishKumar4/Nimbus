import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compiledBodies } from '../../../scripts/lib/compiled-bodies.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const libraries = {
  npa: 'npm-package-arg',
  hostedGitInfo: 'hosted-git-info',
  npmDefinitions: '@npmcli/config/lib/definitions/index.js',
  envReplace: '@npmcli/config/lib/env-replace.js',
  parseField: '@npmcli/config/lib/parse-field.js',
  typeDefs: '@npmcli/config/lib/type-defs.js',
  typeDescription: '@npmcli/config/lib/type-description.js',
  ini: 'ini',
  nopt: 'nopt',
};
const { module } = await compiledBodies({
  contents: Object.entries(libraries).map(([name, specifier]) => `export { default as ${name} } from ${JSON.stringify(specifier)};`).join('\n'),
  resolveDir: root,
});
writeFileSync(new URL('../src/_shared/npm-libs.generated.ts', import.meta.url),
  `// @ts-nocheck — compiler output; the typed boundary is npm-libs.ts.\n// Generated by scripts/compile-npm-libs.mjs.\n${module}`);
